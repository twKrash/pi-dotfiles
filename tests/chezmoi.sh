#!/bin/sh
# chezmoi source state: init + apply into throwaway homes, never the real one.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
command -v chezmoi >/dev/null || { echo 'chezmoi is required (brew install chezmoi)' >&2; exit 1; }
TMP=$(cd "$(mktemp -d)" && pwd -P)
trap 'rm -rf "$TMP"' EXIT HUP INT TERM

# A semantic no-op merge preserves Pi's compact inline array formatting.
cat >"$TMP/settings-defaults.json" <<'JSON'
{
  "packages": ["npm:example"],
  "subagents": {
    "agentOverrides": {
      "scout": {"skills": ["graphify"]}
    }
  }
}
JSON
cat >"$TMP/pi-settings.json" <<'JSON'
{
  "packages": ["npm:example"],
  "subagents": {
    "agentOverrides": {
      "scout": {"skills": ["graphify"]}
    }
  },
  "defaultTools": ["grep", "find", "ls", "codemode"]
}
JSON
node "$ROOT/scripts/merge-json.mjs" settings "$TMP/settings-defaults.json" \
  <"$TMP/pi-settings.json" >"$TMP/merged-settings.json"
cmp "$TMP/pi-settings.json" "$TMP/merged-settings.json"

# Permission merge only tightens, judged per surface (stdin = current file).
perm() { printf '%s' "$1" | node "$ROOT/scripts/merge-json.mjs" permission "$ROOT/agent/permission-system.json" 2>/dev/null; }
perm '{"permission":{"*":"allow"}}' | node -e 'const p=JSON.parse(require("fs").readFileSync(0,"utf8")).permission; if (p.bash["rm -rf *"]!=="ask") throw new Error("ask not added under allow"); if ("*" in p.bash) throw new Error("repo allow added")'
perm '{"permission":{"*":"deny"}}' | node -e 'const p=JSON.parse(require("fs").readFileSync(0,"utf8")).permission; if (p.bash) throw new Error("ask added under catch-all deny")'
perm '{"permission":{"bash":{"rm *":"deny"}}}' | node -e 'const p=JSON.parse(require("fs").readFileSync(0,"utf8")).permission.bash; if ("rm -rf *" in p) throw new Error("ask added next to a local deny")'
perm '' | node -e 'const p=JSON.parse(require("fs").readFileSync(0,"utf8")).permission; if (p.bash["*"]!=="allow") throw new Error("fresh install incomplete")'

# cz NAME ARGS...: chezmoi with a per-machine HOME, config, state, and destination under $TMP/NAME
# (source: $SRC, default this checkout).
cz() {
  name=$1
  shift
  mkdir -p "$TMP/$name/home"
  HOME="$TMP/$name/home" chezmoi --source="${SRC:-$ROOT}" --destination="$TMP/$name/home" --config="$TMP/$name/chezmoi.toml" \
    --persistent-state="$TMP/$name/state.boltdb" --cache="$TMP/$name/cache" --no-tty "$@" </dev/null
}
# init NAME HARNESSES PROVIDER: non-interactive `chezmoi init` (harnesses separated by /).
init() { cz "$1" init --promptMultichoice "Harnesses on this machine=$2" --promptChoice "Pi subagent model profile=$3"; }
expected_instructions() {
  printf '<!-- Generated by chezmoi from pi-dotfiles for %s. Edit instructions/core.md, instructions/harness-%s.md, %s, or %s, then run chezmoi apply. -->\n\n' "$1" "$1" "$2" "$(dirname -- "$2")/local.$1.md"
  cat "$ROOT/instructions/core.md"
  if [ -f "$ROOT/instructions/harness-$1.md" ]; then printf '\n'; cat "$ROOT/instructions/harness-$1.md"; fi
  if [ -f "$2" ]; then printf '\n'; cat "$2"; fi
  if [ -f "$(dirname -- "$2")/local.$1.md" ]; then printf '\n'; cat "$(dirname -- "$2")/local.$1.md"; fi
}

# A stub `claude` records MCP registrations; the real CLI must never run from tests.
mkdir -p "$TMP/stub-bin"
cat >"$TMP/stub-bin/claude" <<'STUB'
#!/bin/sh
case "$1 $2" in
  "--version "*) echo stub ;;
  "mcp get") grep -qx -- "$3" "$STUB_KNOWN" 2>/dev/null ;;
  "mcp add-json") echo "$5" >>"$STUB_KNOWN"; echo "$5" >>"$STUB_ADDED" ;;
  *) exit 1 ;;
esac
STUB
chmod +x "$TMP/stub-bin/claude"
STUB_KNOWN="$TMP/stub-known"; STUB_ADDED="$TMP/stub-added"
export STUB_KNOWN STUB_ADDED
PATH="$TMP/stub-bin:$PATH"
printf '%s\n' github >"$STUB_KNOWN"
: >"$STUB_ADDED"

# Hybrid Pi + Claude Code machine with the Claude subagent profile and a local overlay.
init hybrid pi/claude claude
grep -qx 'harnesses = \["pi", "claude"\]' "$TMP/hybrid/chezmoi.toml"
grep -qx 'provider = "claude"' "$TMP/hybrid/chezmoi.toml"
grep -qx "sourceDir = \"$ROOT\"" "$TMP/hybrid/chezmoi.toml"
grep -qx 'lessInteractive = true' "$TMP/hybrid/chezmoi.toml"
LOCAL="$TMP/hybrid/local.md"
printf '%s\n' '# Local rules' 'local-only rule' >"$LOCAL"
H="$TMP/hybrid/home"
# Existing Pi settings: unrelated values, custom packages, and local tool limits survive;
# an existing empty MEMORY.md is kept (chezmoi removes empty targets unless marked empty_).
mkdir -p "$H/.pi/agent/extensions/pi-permission-system"
mkdir -p "$H/.config/ai-memory"
# Existing Claude Code settings: local permissions and a local plugin survive the merge;
# local auto-memory is turned off anyway (enforced, not a default).
mkdir -p "$H/.claude"
printf '%s\n' '{"permissions":{"allow":["Read(/x)"]},"enabledPlugins":{"local@mine":true,"caveman@caveman":false},"autoMemoryEnabled":true}' >"$H/.claude/settings.json"
: >"$H/.config/ai-memory/MEMORY.md"
# Pre-existing files chezmoi never wrote: a stricter local permission policy and a symlinked AGENTS.md.
printf '%s\n' '{"piInfrastructureReadPaths":["/local/infra"],"permission":{"*":"deny","bash":{"my-local-cmd":"allow"}}}' >"$H/.pi/agent/extensions/pi-permission-system/config.json"
printf '%s\n' 'linked rules' >"$TMP/hybrid/linked.md"
ln -s "$TMP/hybrid/linked.md" "$H/.pi/agent/AGENTS.md"
node - "$H/.pi/agent/settings.json" "$H/.pi/agent/mcp.json" "$H/.pi/agent/pi-goal.json" <<'NODE'
const fs = require('fs');
fs.writeFileSync(process.argv[4], JSON.stringify({
  rpc: {enabled: false, localNote: 'keep'}, continuationLimits: {automaticTurns: 7}, localOnly: {note: 'keep'}
}));
fs.writeFileSync(process.argv[2], JSON.stringify({
  packages: ['npm:custom-package', 'git:github.com/nicobailon/pi-subagents'], defaultProvider: 'keep-provider', defaultModel: 'keep-model', userSetting: 'keep',
  subagents: {agentOverrides: {scout: {model: 'local/old', thinking: 'high', tools: ['read', 'grep']}, worker: {tools: ['read', 'edit', 'write']}}}
}));
fs.writeFileSync(process.argv[3], JSON.stringify({mcpServers: {local: {url: 'http://localhost'}}}));
NODE
cp "$H/.pi/agent/settings.json" "$TMP/settings-before.json"
# First adoption never replaces pre-existing files silently: without a TTY to confirm, apply stops
# and leaves them alone, after backing every existing managed path up privately.
if cz hybrid apply >"$TMP/adopt.log" 2>&1; then exit 1; fi
grep -q '"\*":"deny"' "$H/.pi/agent/extensions/pi-permission-system/config.json"
test -L "$H/.pi/agent/AGENTS.md"
cmp "$TMP/settings-before.json" "$H/.pi/agent/settings.json"
# complete_backup HOME: the one adoption backup with a COMPLETE marker.
complete_backup() { dirname "$(find "$1/.local/state/pi-dotfiles" -mindepth 2 -maxdepth 2 -name COMPLETE)"; }
BACKUP=$(complete_backup "$H")
test "$(ls -ld "$BACKUP" | cut -c1-10)" = drwx------
grep -q '"\*":"deny"' "$BACKUP/paths/.pi/agent/extensions/pi-permission-system/config.json"
test -L "$BACKUP/paths/.pi/agent/AGENTS.md"
cmp "$TMP/settings-before.json" "$BACKUP/paths/.pi/agent/settings.json"
# The backup list covers every file and symlink chezmoi manages.
LIST=$(sed -n 's/^for rel in \(.*\); do$/\1/p' "$ROOT/home/run_once_before_10-backup-existing.sh.tmpl")
test -n "$LIST"
cz hybrid managed --include=files,symlinks | while IFS= read -r managed; do
  covered=0
  for rel in $LIST; do case "$managed" in "$rel" | "$rel"/*) covered=1 ;; esac; done
  [ "$covered" -eq 1 ] || { echo "not backed up: $managed" >&2; exit 1; }
done
# A legacy setup.sh overlay must be migrated explicitly, never dropped silently.
mkdir -p "$H/.config/pi-dotfiles"
printf '%s\n' 'legacy rule' >"$H/.config/pi-dotfiles/local.md"
if cz hybrid apply --force >"$TMP/legacy-both.log" 2>&1; then exit 1; fi
grep -q 'both .*pi-dotfiles/local.md' "$TMP/legacy-both.log"
mv "$LOCAL" "$TMP/local.md.aside"
if cz hybrid apply --force >"$TMP/legacy.log" 2>&1; then exit 1; fi
grep -q 'move .*pi-dotfiles/local.md' "$TMP/legacy.log"
mv "$TMP/local.md.aside" "$LOCAL"
rm -r "$H/.config/pi-dotfiles"
# Explicit resolution (here: --force, i.e. "overwrite all") then applies the repo state.
cz hybrid apply --force
# Permission policy only tightens an existing file: local rules survive, missing repo deny/ask rules are
# added only where they tighten the local decision (not under a local catch-all deny), repo allow rules never.
node - "$H/.pi/agent/extensions/pi-permission-system/config.json" <<'NODE'
const live = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
if (live.permission['*'] !== 'deny') throw new Error('local catch-all changed');
if (live.permission.bash['my-local-cmd'] !== 'allow') throw new Error('local bash rule lost');
if (!live.piInfrastructureReadPaths.includes('/local/infra')) throw new Error('local path lost');
if ('rm -rf *' in live.permission.bash) throw new Error('repo ask rule loosened a local deny');
if ('*' in live.permission.bash) throw new Error('repo allow rule loosened local policy');
NODE
# Plain files are installed as-is; prompt-opt is executable.
test -x "$H/.local/bin/prompt-opt"
cmp "$ROOT/home/dot_local/bin/executable_prompt-opt" "$H/.local/bin/prompt-opt"
cmp "$ROOT/home/dot_local/bin/prompt-opt-history.mjs" "$H/.local/bin/prompt-opt-history.mjs"
cmp "$ROOT/home/dot_pi/private_agent/private_extensions/prompt-opt-pi.js" "$H/.pi/agent/extensions/prompt-opt-pi.js"
test -f "$H/.config/ai-memory/MEMORY.md"
test ! -s "$H/.config/ai-memory/MEMORY.md"
# Pi's agent directory holds credentials: it and the extension config directories stay private.
for dir in .pi/agent .pi/agent/extensions .pi/agent/extensions/pi-permission-system; do
  test "$(ls -ld "$H/$dir" | cut -c1-10)" = drwx------
done
for file in AGENTS.md prompt_engineering.md prompting-references.md prompt-optimization-playbook.md; do
  cmp "$ROOT/home/ai/prompt_engineering/$file" "$H/ai/prompt_engineering/$file"
done
# The Pi skill is generated from the single lab copy.
for file in prompt_engineering.md prompting-references.md prompt-optimization-playbook.md; do
  cmp "$ROOT/home/ai/prompt_engineering/$file" "$H/.pi/agent/skills/prompt-engineering/references/$file"
done
{
  printf '%s\n' '---' 'name: prompt-engineering' \
    'description: Model-aware prompt creation, optimization, review, comparison, and explanation; use when working with prompts.' '---' ''
  cat "$ROOT/home/ai/prompt_engineering/AGENTS.md"
} >"$TMP/expected-skill.md"
cmp "$TMP/expected-skill.md" "$H/.pi/agent/skills/prompt-engineering/SKILL.md"
# code-standards: one source, a skill per selected harness; instructions only point to it.
{
  printf '%s\n' '---' 'name: code-standards' \
    'description: Design, Python and module-size standards; load before writing, reviewing, or refactoring production code.' '---' ''
  cat "$ROOT/instructions/code-standards.md"
} >"$TMP/expected-code-standards.md"
cmp "$TMP/expected-code-standards.md" "$H/.pi/agent/skills/code-standards/SKILL.md"
cmp "$TMP/expected-code-standards.md" "$H/.claude/skills/code-standards/SKILL.md"
for file in .pi/agent/AGENTS.md .claude/CLAUDE.md; do
  grep -Fq 'load the `code-standards` skill' "$H/$file"
  if grep -q 'PEP 8' "$H/$file"; then exit 1; fi
done
# Each harness gets core + its own addendum + local rules; Pi rules stay out of CLAUDE.md.
expected_instructions pi "$LOCAL" >"$TMP/expected-pi.md"
cmp "$TMP/expected-pi.md" "$H/.pi/agent/AGENTS.md"
expected_instructions claude "$LOCAL" >"$TMP/expected-claude.md"
cmp "$TMP/expected-claude.md" "$H/.claude/CLAUDE.md"
grep -q 'pi-subagents' "$H/.pi/agent/AGENTS.md"
if grep -qE '^<<<<<<< |^=======|^>>>>>>> ' "$H/.pi/agent/AGENTS.md"; then exit 1; fi
if grep -qE 'PI_SESSION_ID|ACTIVE\.md|\.pi/tmp/handoffs' "$H/.pi/agent/AGENTS.md"; then exit 1; fi
grep -Fq 'Check `graphify-out/` relative to that target root' "$H/.pi/agent/AGENTS.md"
if grep -q 'pi-subagents\|codemode' "$H/.claude/CLAUDE.md"; then exit 1; fi
test ! -e "$H/.pi/agent/APPEND_SYSTEM.md"
test ! -e "$H/.codex"
# JSON is merged, not replaced: repo defaults and the Claude profile are added, local values kept.
node - "$H/.pi/agent/settings.json" "$H/.pi/agent/mcp.json" "$H/.pi/agent/pi-goal.json" <<'NODE'
const fs = require('fs');
const goalSettings = JSON.parse(fs.readFileSync(process.argv[4], 'utf8'));
// Managed-run RPC is enabled for the extension; every unrelated local setting survives the merge.
if (goalSettings.rpc.enabled !== true) throw new Error('pi-goal rpc not enabled');
if (goalSettings.rpc.localNote !== 'keep') throw new Error('unrelated rpc settings lost');
if (goalSettings.continuationLimits.automaticTurns !== 7) throw new Error('continuation limits lost');
if (goalSettings.localOnly.note !== 'keep') throw new Error('unknown local pi-goal settings lost');
const s = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const m = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const roles = s.subagents.agentOverrides;
if (s.userSetting !== 'keep') throw new Error('settings overwritten');
if (!s.packages.includes('npm:custom-package')) throw new Error('custom package removed');
if (!s.packages.includes('npm:@twkrash/pi-session-inspector')) throw new Error('repo package missing');
if (s.packages.includes('git:github.com/nicobailon/pi-subagents')) throw new Error('legacy pi-subagents Git package retained');
if (s.packages.filter((pkg) => pkg === 'npm:pi-subagents').length !== 1) throw new Error('npm pi-subagents package missing or duplicated');
if (!s.packages.includes('npm:pi-claude-agent-sdk')) throw new Error('Claude SDK package missing');
if (s.defaultProvider !== 'keep-provider' || s.defaultModel !== 'keep-model') throw new Error('main model defaults changed');
if (roles.scout.model !== 'claude-bridge/claude-haiku-4-5' || roles.scout.thinking !== 'low') throw new Error('Claude scout profile missing');
if (roles.oracle.model !== 'claude-bridge/claude-opus-5-5' || roles.oracle.thinking !== 'high') throw new Error('Claude oracle profile missing');
if (JSON.stringify(roles.scout.tools) !== JSON.stringify(['read', 'grep'])) throw new Error('scout tools changed');
if (JSON.stringify(roles.worker.tools) !== JSON.stringify(['read', 'edit', 'write'])) throw new Error('worker tools changed');
if (!m.mcpServers.local) throw new Error('unrelated MCP server removed');
if (!m.mcpServers.context7?.url) throw new Error('Context7 missing');
NODE
# Applying again is a no-op, even after Pi adds its own keys to settings.json.
node -e 'const f=process.argv[1],fs=require("fs"),j=JSON.parse(fs.readFileSync(f));j.piWroteThis=true;fs.writeFileSync(f,JSON.stringify(j,null,2)+"\n")' "$H/.pi/agent/settings.json"
cz hybrid apply
grep -q piWroteThis "$H/.pi/agent/settings.json"
node - "$H/.claude/settings.json" "$ROOT/claude/settings.json" <<'NODE'
const fs = require('fs');
const live = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const repo = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
if (live.permissions.allow[0] !== 'Read(/x)') throw new Error('local permissions lost');
if (live.enabledPlugins['local@mine'] !== true) throw new Error('local plugin lost');
if (live.enabledPlugins['caveman@caveman'] !== false) throw new Error('local plugin choice overwritten');
for (const key of Object.keys(repo.enabledPlugins)) if (!(key in live.enabledPlugins)) throw new Error('missing plugin ' + key);
for (const key of Object.keys(repo.extraKnownMarketplaces)) if (!(key in live.extraKnownMarketplaces)) throw new Error('missing marketplace ' + key);
if (live.statusLine.command !== repo.statusLine.command) throw new Error('statusLine missing');
if (live.autoMemoryEnabled !== false) throw new Error('Claude auto-memory not disabled');
NODE
# Claude MCP servers are registered once; a server the machine already has is left alone.
grep -qx context7 "$STUB_ADDED"
if grep -qx github "$STUB_ADDED"; then exit 1; fi
test -x "$H/.claude/statusline.sh"
cmp "$ROOT/home/dot_claude/executable_statusline.sh" "$H/.claude/statusline.sh"
test -z "$(cz hybrid diff)"
# MEMORY.md and the cache manifest are created once and never overwritten; ai-mem is installed.
cmp "$ROOT/home/dot_config/private_ai-memory/create_structure.json" "$H/.config/ai-memory/structure.json"
cmp "$ROOT/home/dot_local/bin/executable_ai-mem" "$H/.local/bin/ai-mem"
test -x "$H/.local/bin/ai-mem"
printf '%s\n' 'my memory' >"$H/.config/ai-memory/MEMORY.md"
printf '%s\n' '{"sources": {"mine": {"dir": "/x"}}}' >"$H/.config/ai-memory/structure.json"
cz hybrid apply
grep -qx 'my memory' "$H/.config/ai-memory/MEMORY.md"
grep -q '"mine"' "$H/.config/ai-memory/structure.json"
# The MCP sync script embeds the claude CLI path, so installing claude later reruns it.
cz hybrid execute-template "$(cat "$ROOT/home/run_onchange_after_20-claude-mcp.sh.tmpl")" |
  grep -Fq "# claude CLI: $TMP/stub-bin/claude "
# The old Pi-only MEMORY.md must be merged into the shared one, never left unread;
# an untouched stub or blank file has nothing to migrate and does not block.
cp "$ROOT/home/dot_config/private_ai-memory/create_empty_MEMORY.md" "$H/.pi/agent/MEMORY.md"
cz hybrid apply
printf '\n' >"$H/.pi/agent/MEMORY.md"
cz hybrid apply
printf '%s\n' 'old pi memory' >"$H/.pi/agent/MEMORY.md"
if cz hybrid apply >"$TMP/legacy-memory.log" 2>&1; then exit 1; fi
grep -q 'MEMORY.md is no longer read' "$TMP/legacy-memory.log"
rm "$H/.pi/agent/MEMORY.md"
# Editing local.md flows into every generated instruction file on the next apply.
printf '%s\n' 'updated local rule' >>"$LOCAL"
cz hybrid apply
grep -q 'updated local rule' "$H/.pi/agent/AGENTS.md"
grep -q 'updated local rule' "$H/.claude/CLAUDE.md"
# local.<harness>.md reaches only its own harness, after local.md.
printf '%s\n' 'pi-only rule' >"$TMP/hybrid/local.pi.md"
printf '%s\n' 'claude-only rule' >"$TMP/hybrid/local.claude.md"
cz hybrid apply
grep -q 'pi-only rule' "$H/.pi/agent/AGENTS.md"
if grep -q 'claude-only rule' "$H/.pi/agent/AGENTS.md"; then exit 1; fi
grep -q 'claude-only rule' "$H/.claude/CLAUDE.md"
if grep -q 'pi-only rule' "$H/.claude/CLAUDE.md"; then exit 1; fi
awk '/updated local rule/{a=NR} /claude-only rule/{b=NR} END{exit !(a && b && a<b)}' "$H/.claude/CLAUDE.md"
# A locally edited managed file is never overwritten silently: without a TTY apply fails and keeps it.
printf '%s\n' 'local edit' >>"$H/.pi/agent/extensions/subagent/config.json"
if cz hybrid apply >"$TMP/edit.log" 2>&1; then exit 1; fi
grep -q 'has changed since chezmoi last wrote it' "$TMP/edit.log"
grep -qx 'local edit' "$H/.pi/agent/extensions/subagent/config.json"
cz hybrid apply --force
cmp "$ROOT/home/dot_pi/private_agent/private_extensions/subagent/config.json" "$H/.pi/agent/extensions/subagent/config.json"

# Pi + Codex machine with the Codex (OpenAI) subagent profile and no local overlay.
init home pi/codex codex
cz home apply
# Without the claude harness nothing is registered.
test "$(wc -l <"$STUB_ADDED")" -eq 1
C="$TMP/home/home"
cmp "$ROOT/home/dot_config/private_ai-memory/create_empty_MEMORY.md" "$C/.config/ai-memory/MEMORY.md"
expected_instructions codex "$TMP/home/local.md" >"$TMP/expected-codex.md"
cmp "$TMP/expected-codex.md" "$C/.codex/AGENTS.md"
# A fresh install gets the full repo permission defaults.
node - "$C/.pi/agent/extensions/pi-permission-system/config.json" "$ROOT/agent/permission-system.json" <<'NODE'
const fs = require('fs');
const live = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const repo = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
if (JSON.stringify(live.permission) !== JSON.stringify(repo.permission)) throw new Error('fresh install differs from repo defaults');
NODE
grep -q 'main chat as the orchestrator' "$C/.codex/AGENTS.md"
grep -q 'task-specific handoff note' "$C/.codex/AGENTS.md"
if grep -q 'pi-subagents\|codemode' "$C/.codex/AGENTS.md"; then exit 1; fi
# Codex gets the code-standards skill its instructions point to.
grep -Fq 'load the `code-standards` skill' "$C/.codex/AGENTS.md"
cmp "$TMP/expected-code-standards.md" "$C/.codex/skills/code-standards/SKILL.md"
test ! -e "$C/.claude"
node - "$C/.pi/agent/settings.json" <<'NODE'
const s = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
const roles = s.subagents.agentOverrides;
if (roles.scout.model !== 'openai/gpt-6-luna') throw new Error('Codex scout profile missing');
if (roles.oracle.model !== 'openai/gpt-6.1-sol') throw new Error('Codex oracle profile missing');
if (s.packages.includes('npm:pi-claude-agent-sdk')) throw new Error('Claude SDK added to Codex profile');
NODE

# A parent that is a symlink or a plain file is saved as-is (chezmoi would replace it with a directory),
# and nothing is copied through it.
init parents pi/claude none
P="$TMP/parents/home"
mkdir -p "$TMP/parents/elsewhere"
printf '%s\n' 'original claude rules' >"$TMP/parents/elsewhere/CLAUDE.md"
ln -s "$TMP/parents/elsewhere" "$P/.claude"
printf '%s\n' 'ai is a file' >"$P/ai"
if cz parents apply >/dev/null 2>&1; then exit 1; fi
test -L "$P/.claude"
grep -qx 'ai is a file' "$P/ai"
PB=$(complete_backup "$P")
test -L "$PB/ancestors/.claude"
test "$(readlink "$PB/ancestors/.claude")" = "$TMP/parents/elsewhere"
test ! -e "$PB/paths/.claude"
grep -qx 'ai is a file' "$PB/ancestors/ai"
cz parents apply --force
grep -qx 'original claude rules' "$TMP/parents/elsewhere/CLAUDE.md"

# A failed backup attempt is never reused: the retry gets a fresh directory, and only it is COMPLETE
# (no directory nesting from copying into a partial snapshot). A fixed `date` makes both attempts
# share one timestamp, the case where a timestamp-named directory would be reused.
mkdir -p "$TMP/fixed-date"
printf '#!/bin/sh\necho 20260101000000\n' >"$TMP/fixed-date/date"
chmod +x "$TMP/fixed-date/date"
init retry pi none
Y="$TMP/retry/home"
mkdir -p "$Y/ai/prompt_engineering" "$Y/.pi/agent" "$Y/.config/ai-memory"
printf '%s\n' 'my lab' >"$Y/ai/prompt_engineering/AGENTS.md"
printf '%s\n' 'my memory' >"$Y/.config/ai-memory/MEMORY.md"
chmod 000 "$Y/.config/ai-memory/MEMORY.md"
if (PATH="$TMP/fixed-date:$PATH" && export PATH && cz retry apply >/dev/null 2>&1); then chmod 644 "$Y/.config/ai-memory/MEMORY.md"; exit 1; fi
chmod 644 "$Y/.config/ai-memory/MEMORY.md"
if (PATH="$TMP/fixed-date:$PATH" && export PATH && cz retry apply >/dev/null 2>&1); then exit 1; fi
test "$(find "$Y/.local/state/pi-dotfiles" -mindepth 1 -maxdepth 1 -name 'adoption-backup-*' | wc -l)" -eq 2

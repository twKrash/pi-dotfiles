#!/bin/sh
set -eu

ROOT=$(CDPATH= cd "$(dirname "$0")/.." && pwd)
AGENT_DIR=${PI_CODING_AGENT_DIR:-"$HOME/.pi/agent"}
DRY_RUN=0
FORCE=0
INTERACTIVE=0
exec 3<&0
CONFIG_DIR=${PI_DOTFILES_CONFIG_DIR:-"$HOME/.config/pi-dotfiles"}
USAGE="Usage: $0 [--dry-run] [--force] [--interactive] [--provider=codex|claude] [pi] [claude] [codex]
Harnesses are required on the first run and remembered in $CONFIG_DIR/harnesses."
PROVIDER=
HARNESSES=
for arg do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --force) FORCE=1 ;;
    --interactive) INTERACTIVE=1 ;;
    --provider=*)
      PROVIDER=${arg#*=}
      case "$PROVIDER" in
        codex|claude) ;;
        *) printf 'Unsupported provider: %s (choose codex or claude)\n' "$PROVIDER" >&2; exit 2 ;;
      esac
      ;;
    pi|claude|codex) HARNESSES="$HARNESSES $arg" ;;
    -h|--help) printf '%s\n' "$USAGE"; exit 0 ;;
    *) printf 'Unknown option or harness: %s\n' "$arg" >&2; exit 2 ;;
  esac
done
if [ -z "$HARNESSES" ] && [ -f "$CONFIG_DIR/harnesses" ]; then
  HARNESSES=$(cat "$CONFIG_DIR/harnesses")
fi
[ -n "$HARNESSES" ] || { printf 'Choose at least one harness.\n%s\n' "$USAGE" >&2; exit 2; }
HARNESSES=$(echo $HARNESSES)
if [ "$DRY_RUN" -eq 0 ]; then
  mkdir -p "$CONFIG_DIR"
  printf '%s\n' "$HARNESSES" >"$CONFIG_DIR/harnesses"
fi
printf 'HARNESSES %s\n' "$HARNESSES"
has_harness() { case " $HARNESSES " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

run_merge() {
  kind=$1 src=$2 dst=$3 profile=${4:-}
  if PI_DOTFILES_DRY_RUN=$DRY_RUN PI_DOTFILES_FORCE=$FORCE node "$ROOT/scripts/merge-json.mjs" "$kind" "$src" "$dst" "$profile"; then
    return 0
  else
    result=$?
    [ "$result" -eq 3 ] || return "$result"
  fi
}

copy_one() {
  src=$1 target=$2 create_only=${3:-no}
  if [ -L "$target" ]; then
    printf 'CONFLICT symlink preserved %s\n' "$target"
    return
  fi
  if [ "$create_only" = yes ] && [ -e "$target" ]; then
    printf 'PRESERVED %s\n' "$target"
    return
  fi
  if [ -f "$target" ] && cmp -s "$src" "$target"; then
    printf 'UNCHANGED %s\n' "$target"
    return
  fi
  if [ -e "$target" ] && [ "$FORCE" -ne 1 ]; then
    candidate="$target.pi-dotfiles-new"
    if [ "$INTERACTIVE" -eq 1 ]; then
      printf 'Conflict: %s\n  [u] update from repo (backup local)\n  [k] keep local and stage repo candidate\n  [s] skip\nChoice [s]: ' "$target" >&2
      IFS= read -r choice <&3 || { printf '\nNo choice received; preserving %s\n' "$target" >&2; return; }
      case "$choice" in
        u|U) ;;
        k|K)
          printf 'KEEP %s; candidate: %s\n' "$target" "$candidate"
          if [ "$DRY_RUN" -eq 0 ]; then
            if [ -e "$candidate" ] || [ -L "$candidate" ]; then
              printf 'CANDIDATE preserved %s\n' "$candidate"
            else
              cp "$src" "$candidate"
            fi
          fi
          return
          ;;
        *)
          printf 'SKIP %s\n' "$target"
          return
          ;;
      esac
    else
      printf 'CONFLICT preserved %s; candidate: %s.pi-dotfiles-new\n' "$target" "$target"
      if [ "$DRY_RUN" -eq 0 ]; then
        if [ -e "$candidate" ] || [ -L "$candidate" ]; then
          printf 'CANDIDATE preserved %s\n' "$candidate"
        else
          cp "$src" "$candidate"
        fi
      fi
      return
    fi
  fi
  printf '%s %s\n' "$([ "$DRY_RUN" -eq 1 ] && printf 'WOULD COPY' || printf 'COPY')" "$target"
  if [ "$DRY_RUN" -eq 1 ]; then return; fi
  mkdir -p "$(dirname "$target")"
  if [ -e "$target" ]; then
    backup="$target.pi-dotfiles-bak.$(date '+%Y%m%d%H%M%S').$$"
    cp -p "$target" "$backup"
    printf 'BACKUP %s\n' "$backup"
  fi
  tmp="$target.pi-dotfiles-tmp.$$"
  cp -p "$src" "$tmp"
  mv -f "$tmp" "$target"
}

copy_tree() {
  srcdir=$1 destdir=$2
  find "$srcdir" -type f -print | while IFS= read -r src; do
    rel=${src#"$srcdir"/}
    copy_one "$src" "$destdir/$rel"
  done
}

# Each harness gets its own global instructions file: shared core + harness addendum + local rules.
install_instructions() {
  harness=$1 target=$2
  instructions_tmp=$(mktemp)
  {
    printf '<!-- Generated by pi-dotfiles setup.sh for %s. Edit instructions/core.md, instructions/harness-%s.md, or %s/local.md and re-run setup. -->\n\n' "$harness" "$harness" "$CONFIG_DIR"
    cat "$ROOT/instructions/core.md"
    if [ -f "$ROOT/instructions/harness-$harness.md" ]; then printf '\n'; cat "$ROOT/instructions/harness-$harness.md"; fi
    if [ -f "$CONFIG_DIR/local.md" ]; then printf '\n'; cat "$CONFIG_DIR/local.md"; fi
  } >"$instructions_tmp"
  chmod 644 "$instructions_tmp"
  copy_one "$instructions_tmp" "$target"
  rm -f "$instructions_tmp"
}

if has_harness pi; then
  PROFILE=
  [ -z "$PROVIDER" ] || PROFILE="$ROOT/agent/providers/$PROVIDER.json"
  run_merge settings "$ROOT/agent/settings.json" "$AGENT_DIR/settings.json" "$PROFILE"
  run_merge mcp "$ROOT/agent/mcp.json" "$AGENT_DIR/mcp.json"
  copy_one "$ROOT/bin/prompt-opt" "$HOME/.local/bin/prompt-opt"
  copy_one "$ROOT/bin/prompt-opt-history.mjs" "$HOME/.local/bin/prompt-opt-history.mjs"
  copy_tree "$ROOT/prompt_engineering" "$HOME/ai/prompt_engineering"
  copy_one "$ROOT/agent/MEMORY.md.template" "$AGENT_DIR/MEMORY.md" yes
  copy_tree "$ROOT/agent/extensions" "$AGENT_DIR/extensions"

  skill_tmp=$(mktemp)
  trap 'rm -f "$skill_tmp"' EXIT HUP INT TERM
  # Pi always loads the global AGENTS.md, but a trusted project's .pi/APPEND_SYSTEM.md
  # replaces the global one, so the Pi addendum is installed inside AGENTS.md.
  install_instructions pi "$AGENT_DIR/AGENTS.md"
  {
    cat <<'SKILL_HEADER'
---
name: prompt-engineering
description: Model-aware prompt creation, optimization, review, comparison, and explanation; use when working with prompts.
---

SKILL_HEADER
    cat "$ROOT/prompt_engineering/AGENTS.md"
  } >"$skill_tmp"
  chmod 644 "$skill_tmp"
  copy_one "$skill_tmp" "$AGENT_DIR/skills/prompt-engineering/SKILL.md"
  rm -f "$skill_tmp"
  trap - EXIT HUP INT TERM
  for file in prompt_engineering.md prompting-references.md prompt-optimization-playbook.md; do
    copy_one "$ROOT/prompt_engineering/$file" "$AGENT_DIR/skills/prompt-engineering/references/$file"
  done
fi
if has_harness claude; then
  install_instructions claude "${CLAUDE_CONFIG_DIR:-$HOME/.claude}/CLAUDE.md"
fi
if has_harness codex; then
  install_instructions codex "${CODEX_HOME:-$HOME/.codex}/AGENTS.md"
fi
